import { describe, it, expect, beforeEach, afterEach } from "bun:test";
import fs from "node:fs";
import path from "node:path";
import { JsonFileStore } from "../src/store.js";
import { PatchService } from "../src/service.js";
import { MockAiProvider, DefaultAiService, GeminiAiProvider } from "../src/ai.js";
import type { Patch, VerificationRun } from "@patchwork/contracts";

const TEST_DB_PATH = path.join(import.meta.dirname, "test-ai-service-db.json");

function cleanup() {
  if (fs.existsSync(TEST_DB_PATH)) fs.unlinkSync(TEST_DB_PATH);
}

beforeEach(cleanup);
afterEach(cleanup);

describe("AI Service & Mock Engine", () => {
  it("generates a valid, allowlisted patch proposal from natural language prompt", async () => {
    const provider = new MockAiProvider();
    const aiService = new DefaultAiService(provider);

    const proposal = await aiService.generatePatchProposal({
      websiteId: "demo-store",
      prompt: "The checkout button is invisible on mobile. Restore it without changing the desktop layout.",
      elementContext: {
        tag: "button",
        selector: "#checkout-btn",
        role: "button",
      },
    });

    expect(proposal.name).toContain("checkout button");
    expect(proposal.targetFingerprint.selector).toBe("#checkout-btn");
    expect(proposal.operation.type).toBe("style.set");
    expect(proposal.explanation).toBeTruthy();
    expect(proposal.assumptions?.length).toBeGreaterThan(0);
    expect(proposal.confidence).toBeGreaterThan(0.7);
  });

  it("strictly validates and rejects any disallowed operations generated by an untrusted provider", async () => {
    // Custom mock provider returning an invalid operation
    const rogueProvider = {
      async generatePatch() {
        return {
          name: "Injected script",
          targetFingerprint: { tag: "body", selector: "body" },
          operation: { type: "script.eval", code: "alert(1)" } as any,
          explanation: "Dangerous operation",
        };
      },
      async explainVerification() {
        throw new Error("not used");
      },
      async disambiguateTarget() {
        throw new Error("not used");
      },
    };

    const aiService = new DefaultAiService(rogueProvider);

    await expect(
      aiService.generatePatchProposal({
        websiteId: "demo-store",
        prompt: "Make a script",
      })
    ).rejects.toThrow("Unsupported operation type");
  });

  it("explains verification failure separating observed facts from hypotheses", async () => {
    const provider = new MockAiProvider();
    const aiService = new DefaultAiService(provider);

    const dummyPatch: Patch = {
      id: "patch-checkout-1",
      websiteId: "demo-store",
      name: "Checkout green",
      status: "verification_failed",
      currentVersion: 1,
      versions: [],
      targetFingerprint: { tag: "button", selector: "#checkout-btn" },
      operation: { type: "style.set", property: "background-color", value: "#10b981" },
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
    };

    const dummyRun: VerificationRun = {
      id: "run-failed-123",
      patchId: dummyPatch.id,
      websiteId: "demo-store",
      status: "failed",
      viewport: { width: 1280, height: 800 },
      startedAt: new Date().toISOString(),
      completedAt: new Date().toISOString(),
      durationMs: 1500,
      assertions: [
        {
          assertionId: "desktop-target-unique",
          passed: false,
          errorMessage: "Target element '#checkout-btn' not found on page (DOM Drift Detected).",
        },
      ],
      error: "Target element '#checkout-btn' not found on page (DOM Drift Detected).",
    };

    const explanation = await aiService.explainVerificationFailure({
      run: dummyRun,
      patch: dummyPatch,
    });

    expect(explanation.runId).toBe("run-failed-123");
    expect(explanation.observedFacts.length).toBeGreaterThan(0);
    expect(explanation.observedFacts.some((f) => f.includes("#checkout-btn"))).toBe(true);
    expect(explanation.hypotheses.length).toBeGreaterThan(0);
    expect(explanation.recommendedActions.length).toBeGreaterThan(0);
  });

  it("disambiguates multiple drift candidate targets with ranking and reasoning", async () => {
    const provider = new MockAiProvider();
    const aiService = new DefaultAiService(provider);

    const dummyPatch: Patch = {
      id: "patch-checkout-2",
      websiteId: "demo-store",
      name: "Checkout CTA",
      status: "stale",
      currentVersion: 1,
      versions: [],
      targetFingerprint: {
        tag: "button",
        selector: "#checkout-btn",
        text: "Complete Order",
        role: "button",
      },
      operation: { type: "style.set", property: "background-color", value: "#10b981" },
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
    };

    const candidates = [
      {
        selector: "#pay-now-action",
        tag: "button",
        score: 0.92,
        tier: "high",
        text: "Complete Order",
        role: "button",
        parentContext: "payment-drawer",
      },
      {
        selector: ".back-to-cart",
        tag: "a",
        score: 0.45,
        tier: "low",
        text: "Back to Cart",
        role: "link",
        parentContext: "cart-footer",
      },
    ];

    const result = await aiService.disambiguateTarget({
      patch: dummyPatch,
      candidates,
    });

    expect(result.recommendedSelector).toBe("#pay-now-action");
    expect(result.candidateRankings[0].selector).toBe("#pay-now-action");
    expect(result.candidateRankings[0].rank).toBe(1);
    expect(result.reasoning).toContain("Complete Order");
  });

  it("generates element.insert proposal from prompt requesting to add a banner", async () => {
    const provider = new MockAiProvider();
    const aiService = new DefaultAiService(provider);

    const proposal = await aiService.generatePatchProposal({
      websiteId: "demo-store",
      prompt: "Add a free shipping announcement banner above the checkout summary",
      elementContext: {
        tag: "div",
        selector: "#checkout-summary",
      },
    });

    expect(proposal.operation.type).toBe("element.insert");
    const insertOp = proposal.operation as any;
    expect(insertOp.tag).toBe("div");
    expect(insertOp.position).toBe("before");
    expect(insertOp.textContent).toContain("Shipping");
    expect(proposal.targetFingerprint.selector).toBe("#checkout-summary");
  });

  it("generates element.remove proposal from prompt requesting to delete an element", async () => {
    const provider = new MockAiProvider();
    const aiService = new DefaultAiService(provider);

    const proposal = await aiService.generatePatchProposal({
      websiteId: "demo-store",
      prompt: "Delete the seasonal holiday banner from the page",
      elementContext: {
        tag: "div",
        selector: ".holiday-banner",
      },
    });

    expect(proposal.operation.type).toBe("element.remove");
    expect(proposal.name).toContain("Delete");
    expect(proposal.targetFingerprint.selector).toBe(".holiday-banner");
  });

  it("GeminiAiProvider falls back gracefully when API key is missing or invalid", async () => {
    const gemini = new GeminiAiProvider({
      apiKey: "",
      model: "gemini-3.5-flash-lite",
    });

    expect(gemini.getProviderName()).toBe("mock");

    const proposal = await gemini.generatePatch({
      websiteId: "demo-store",
      prompt: "Change checkout button background to emerald green",
      elementContext: { tag: "button", selector: "#checkout-btn" },
    });

    expect(proposal.operation.type).toBe("style.set");
    expect((proposal.operation as any).value).toBe("#10b981");
  });

  it("GeminiAiProvider parses structured JSON responses from model endpoint", async () => {
    const originalFetch = globalThis.fetch;
    try {
      globalThis.fetch = async (url: any, init: any) => {
        return {
          ok: true,
          status: 200,
          json: async () => ({
            candidates: [
              {
                content: {
                  parts: [
                    {
                      text: JSON.stringify({
                        name: "Add Promo Announcement",
                        targetFingerprint: { tag: "header", selector: "header" },
                        operation: {
                          type: "element.insert",
                          tag: "div",
                          position: "prepend",
                          textContent: "Cyber Week Sale!",
                        },
                        explanation: "Adds promotional banner at top of header",
                        assumptions: ["Header exists"],
                        confidence: 0.98,
                      }),
                    },
                  ],
                },
              },
            ],
          }),
        } as any;
      };

      const gemini = new GeminiAiProvider({
        apiKey: "fake-key-for-test",
        model: "gemini-3.5-flash-lite",
      });

      expect(gemini.getProviderName()).toBe("gemini-3.5-flash-lite");

      const proposal = await gemini.generatePatch({
        websiteId: "demo-store",
        prompt: "Add a Cyber Week banner inside header",
      });

      expect(proposal.name).toBe("Add Promo Announcement");
      expect(proposal.operation.type).toBe("element.insert");
      expect((proposal.operation as any).textContent).toBe("Cyber Week Sale!");
      expect(proposal.confidence).toBe(0.98);
    } finally {
      globalThis.fetch = originalFetch;
    }
  });
});
